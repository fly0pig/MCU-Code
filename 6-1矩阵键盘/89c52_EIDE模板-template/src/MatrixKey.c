#include <STC89C5xRC.h>
#include "Delay.h"

/*
 * 函数名：MatrixKey
 * 功  能：4x4 矩阵按键扫描
 * 返回值：按下按键对应的键值；无按键时返回 0
 *
 * 硬件连接假设：
 *   P1.0 ~ P1.3 —— 4 根列线（输出低电平，逐列扫描）
 *   P1.4 ~ P1.7 —— 4 根行线（输入，读取行状态）
 *
 * 扫描原理：
 *   1) 先让 P1 全部写 1（准双向口读引脚前必须写 1，否则读回恒为 0）
 *   2) 拉低某一列，其它列保持高电平
 *   3) 依次读 P14~P17 四根行线，哪一行为 0，说明该行与该列交叉处的按键被按下
 *   4) 消抖后返回对应键值
/*
 * ====================================================================
 * 矩阵键盘 键值与返回值映射表（完全按照你的原版键位）：
 * 
 *  ┌──────┬──────┬──────┬──────┐
 *  │  10  │  11  │  12  │  15  │  (10:'+', 11:'-', 12:'*', 15:'/')
 *  ├──────┼──────┼──────┼──────┤
 *  │  7   │  8   │  9   │  0   │  (0 就是纯数字 0)
 *  ├──────┼──────┼──────┼──────┤
 *  │  4   │  5   │  6   │  14  │  (14 代表 'D' 退格键)
 *  ├──────┼──────┼──────┼──────┤
 *  │  1   │  2   │  3   │  13  │  (13 代表 'Y' 确认键)
 *  └──────┴──────┴──────┴──────┘
 * 
 * 返回值说明：
 *   没有按键按下时，返回 255 (0xFF)
 *   按下数字键，返回 0~9
 *   按下符号键，返回 10~15 
 * ====================================================================
 */
//按列扫描按键矩阵，返回按键编号
unsigned char MatrixKey(void)
{
    unsigned char KeyNumber = 0xFF;// ★ 初始值改为 0xFF，代表无按键
    
    //第1列按键扫描
{
    P1 = 0xFF; //设置P1口低四位为输入，高四位为输出
    P13 = 0; //拉低P13，检测第一列按键
    if (P14 == 0) 
    {
        Delay(20); //消抖
        if (P14 == 0)
        {
           while (P14 == 0); //等待按键释放
        Delay(20); //消抖
        KeyNumber = 1; //按键编号为1
        }
        
       

    }else if (P15 == 0) {
        Delay(20); //消抖

        if (P15 == 0)
        {
        while (P15 == 0); //等待按键释放
        Delay(20); //消抖
        KeyNumber = 4; //按键编号为4
        }
    }else if (P16 == 0){

        Delay(20); //消抖
        if (P16 == 0)
        {
        while (P16 == 0); //等待按键释放
        Delay(20); //消抖
        KeyNumber = 7; //按键编号为7
        }

    }else if (P17 == 0){
        Delay(20); //消抖
        if (P17 == 0)
        {
        while (P17 == 0); //等待按键释放
        Delay(20); //消抖
        KeyNumber = 10; //按键为符号+(Plus)
        }
    }
}
    //第2列按键扫描
{
    P1 = 0xFF; //设置P1口低四位为输入，高四位为输出
    P12 = 0; //拉低P12，检测第二列按键
    if (P14 == 0) 
    {
        Delay(20); //消抖
        if (P14 == 0)
        {
            while (P14 == 0); //等待按键释放
            Delay(20); //消抖
            KeyNumber = 2; //按键编号为2
        }
    }else if (P15 == 0)
    {
        Delay(20); //消抖
        if (P15 == 0)
        {
            while (P15 == 0); //等待按键释放
            Delay(20); //消抖
            KeyNumber = 5; //按键编号为5
        }
    }else if (P16 == 0)
    {
        Delay(20); //消抖
        if (P16 == 0)
        {
            while (P16 == 0); //等待按键释放
            Delay(20); //消抖
            KeyNumber = 8; //按键编号为8
        }
    }else if (P17 == 0)
    {
        Delay(20); //消抖
        if (P17 == 0)
        {
            while (P17 == 0); //等待按键释放
            Delay(20); //消抖
            KeyNumber = 11; //按键编号为-
        }
    }
}
    //第3列按键扫描
{
    P1 = 0xFF; //设置P1口低四位为输入，高四位为输出
    P11 = 0; //拉低P11，检测第三列按键
    if (P14 == 0) 
    {
        Delay(20); //消抖
        if (P14 == 0)
        {
            while (P14 == 0); //等待按键释放
            Delay(20); //消抖
            KeyNumber = 3; //按键编号为3
        }
    }else if (P15 == 0)
    {
        Delay(20); //消抖
        if (P15 == 0)
        {
            while (P15 == 0); //等待按键释放
            Delay(20); //消抖
            KeyNumber = 6; //按键编号为6
        }
    }else if (P16 == 0)
    {
        Delay(20); //消抖
        if (P16 == 0)
        {
            while (P16 == 0); //等待按键释放
            Delay(20); //消抖
            KeyNumber = 9; //按键编号为9
        }
    }else if (P17 == 0)
    {
        Delay(20); //消抖
        if (P17 == 0)
        {
            while (P17 == 0); //等待按键释放
            Delay(20); //消抖
            KeyNumber = 12; //按键编号为*
        }
    }

}
//第4列按键扫描
{
  
    P1 = 0xFF; //设置P1口低四位为输入，高四位为输出
    P10 = 0; //拉低P10，检测第四列按键
    if (P14 == 0) 
    {
        Delay(20); //消抖
        if (P14 == 0)
        {
            while (P14 == 0); //等待按键释放
            Delay(20); //消抖
            KeyNumber = 13; //按键为确认Yes
        }
    }else if (P15 == 0)
    {
        Delay(20); //消抖
        if (P15 == 0)
        {
            while (P15 == 0); //等待按键释放
            Delay(20); //消抖
            KeyNumber = 14; //按键为删除“Delate”
        }
    }else if (P16 == 0)
    {
        Delay(20); //消抖
        if (P16 == 0)
        {
            while (P16 == 0); //等待按键释放
            Delay(20); //消抖
            KeyNumber = 0; //按键编号为0
        }
    }else if (P17 == 0)
    {
        Delay(20); //消抖
        if (P17 == 0)
        {
            while (P17 == 0); //等待按键释放
            Delay(20); //消抖
            KeyNumber = 15; //按键编号为/
        }
    }
}
    
    
    return KeyNumber;
}